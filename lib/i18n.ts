export type Dictionary = typeof en;

export function dictionary(lang: Lang): Dictionary {
  return lang === "fr" ? fr : en;
}

export function pickLang(cookieValue: string | undefined, acceptLanguage: string | null): Lang {
  if (cookieValue === "fr" || cookieValue === "en") return cookieValue;
  return acceptLanguage?.toLowerCase().startsWith("fr") ? "fr" : "en";
}
